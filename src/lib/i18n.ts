const messages: Record<Language, Record<TranslationKey, Message>> = { en: english, zh: chinese };

export const isTranslationKey = (key: unknown): key is TranslationKey =>
  typeof key === 'string' && Object.hasOwn(english, key);

export function translate(
  key: TranslationKey,
  language: Language = 'en',
  params: TranslationParams = {}
): string {
  const message = messages[language]?.[key] ?? english[key];
  if (!message) return key;
  const localizedParams = { ...params };
  if (typeof params.category === 'string') {
    localizedParams.category = categoryLabel(params.category, language);
  }
  if (typeof params.tag === 'string') {
    localizedParams.tag = tagLabel(params.tag, language);
  }
  const text = typeof message === 'function' ? message(localizedParams) : message;
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    String(localizedParams[name] ?? match)
  );
}
